package com.tal.redalert

/**
 * "מה לעשות" - הנחיות קצרות לפי סוג האיום.
 * מבוסס על הנחיות ההתגוננות הכלליות של פיקוד העורף. ההנחיות הרשמיות (oref.org.il) גוברות תמיד.
 */
object Guidance {

    fun forTitle(title: String): List<String> = when {
        title.contains("הסתיים") -> listOf(
            "ניתן לצאת מהמרחב המוגן",
            "המשיכו לעקוב אחרי התראות – ייתכנו התראות נוספות"
        )
        title.contains("בדקות הקרובות") || title.contains("מקדימה") -> listOf(
            "התקרבו למרחב מוגן – היו במקום שממנו תספיקו להגיע אליו בזמן",
            "עקבו אחרי ההתראות"
        )
        title.contains("מחבלים") -> listOf(
            "היכנסו מיד למבנה, נעלו דלתות וחלונות",
            "כבו אורות, התרחקו מחלונות ודלתות",
            "הישארו בפנים עד הודעה, והישמעו לכוחות הביטחון"
        )
        title.contains("רעידת אדמה") -> listOf(
            "צאו לשטח פתוח אם אפשר לעשות זאת מיד",
            "אם לא – ממ\"ד או חדר מדרגות. לא במעלית",
            "התרחקו ממבנים, עמודים וחוטי חשמל"
        )
        title.contains("צונאמי") -> listOf(
            "התרחקו מיד מחוף הים",
            "עלו לשטח גבוה או לקומה עליונה של מבנה יציב"
        )
        title.contains("חומרים מסוכנים") || title.contains("רדיולוגי") || title.contains("כימי") -> listOf(
            "היכנסו למבנה, לחדר פנימי או למרחב מוגן",
            "סגרו חלונות ודלתות, כבו מזגנים ואוורור",
            "הישארו בפנים עד הודעה"
        )
        // ירי רקטות וטילים, חדירת כלי טיס עוין, התרעה כללית
        else -> listOf(
            "היכנסו למרחב המוגן וסגרו דלת וחלון",
            "אין מרחב מוגן – חדר פנימי או חדר מדרגות, רחוק מחלונות",
            "בחוץ – שכבו על הקרקע והגנו על הראש בידיים",
            "ברכב – עצרו בצד, צאו והתרחקו מהרכב",
            "הישארו עד הודעה על סיום האירוע"
        )
    }
}
